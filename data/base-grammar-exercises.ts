export function baseGrammarExercises(week: number): Exercise[] {
  return blanks[week - 1].map(([before, answer, after, wrong1, wrong2], i) => {
    const point = intensiveWeek(week).grammar[i];
    const choices = [answer, wrong1, wrong2], n = (week + i) % 3;
    return { id: `grammar-base-w${week}-${i}`, week, skill: "grammar", prompt: `${before}〔　〕${after}`, options: [...choices.slice(n), ...choices.slice(0, n)], accepted: [answer], explanation: `${point.explanation} 注意：${point.caution}`, sourceTitle: point.form };
  });
}
