export function dialoguePracticeTasks(
  lesson: ImmersionLesson,
  section: ImmersionSection,
): DialoguePracticeTask[] {
  const week = Math.min(
    26,
    Math.max(1, section.review ? section.source.week : lesson.week),
  );
  const tasks: DialoguePracticeTask[] = [];
  const questionIndex = section.lines.findIndex(
    (line, index) =>
      line.ko.includes("?") &&
      !!section.lines[index + 1] &&
      section.lines[index + 1].speaker !== line.speaker,
  );
  const responseIndex =
    questionIndex >= 0
      ? questionIndex
      : section.lines.findIndex(
          (line, index) =>
            section.lines[index + 1] &&
            section.lines[index + 1].speaker !== line.speaker,
        );
  if (responseIndex >= 0 && section.kind !== "passage") {
    const cue = section.lines[responseIndex];
    const answer = section.lines[responseIndex + 1];
    tasks.push({
      id: "current-reply",
      title: "自己接一句",
      kind: "reply",
      source: "current",
      prompt: `这是刚学过的「${section.label}」。只看对方这句话，按原场景信息独立回应；也可以用你自己的礼貌说法。写完再核对。`,
      stimulus: [cue.ko],
      stimulusLineIds: [cue.id],
      referenceKo: [answer.ko],
      referenceLineIds: [answer.id],
      referenceZh: `原文回应：${answer.zh}（熟悉场景回忆；不是未见测试，措辞不必完全相同。）`,
      checklist: [
        "回应了对方真正的问题或意图",
        "信息和原场景一致",
        "语尾与角色关系一致",
      ],
      supportedGoals: ["回应对方当前的问题或意图，保留原场景已给出的信息"],
    });
  } else {
    const single = section.lines.length <= 1 || section.kind === "sentence";
    const short = section.lines.length <= 6;
    const pronunciation = section.kind === "pronunciation";
    const excerpts = [
      section.lines[0],
      section.lines[Math.floor(section.lines.length / 2)],
      section.lines.at(-1),
    ].filter((line): line is ImmersionSection["lines"][number] => !!line);
    tasks.push({
      id: "current-summary",
      title: pronunciation
        ? "回忆音节或短表达"
        : single
          ? "复述或改写原句"
          : week >= 19 && !short
            ? "书面摘要"
            : "说清材料信息",
      kind: "summary",
      source: "current",
      prompt: pronunciation
        ? `暂时不回看「${section.label}」，从记忆写出听到的音节或短表达，再揭晓核对。不要求扩写情节或观点。`
        : single
          ? `暂时不回看「${section.label}」，用 1–2 句韩语复述或改写原句的意思，保留原句的条件、否定和所指；不扩写原文没有的人物、理由或意见。`
          : short
            ? `暂时不回看「${section.label}」，用 1–3 句韩语说清材料实际提供的信息。可连接或改写已有细节，不补写材料没有的理由、不同意见或结果。`
            : `读过「${section.label}」后，暂时不回看正文，用 ${week >= 19 ? "4–6" : "3–5"} 个韩语句子概括材料讨论的事项和关键内容。只归纳原文已有的理由、不同意见或结果；材料未说明的内容不补写。${week >= 19 ? "统一使用书面语体。" : "可改变措辞，不增加原文没有的事实。"}`,
      stimulus: [],
      referenceKo: [...new Set(excerpts.map((line) => line.ko))],
      referenceLineIds: [...new Set(excerpts.map((line) => line.id))],
      referenceZh: `以下是供核对事实的原文节选，并非摘要范文：${excerpts.map((line) => line.zh).join(" ")}`,
      checklist: pronunciation
        ? ["回忆了材料中的音节或短表达", "核对遗漏的字母和收音，不推算发音分数"]
        : single
          ? [
              "原句的主要意思准确",
              "条件、否定和所指没有改变",
              "没有添加未经说明的事实",
            ]
          : [
              "材料的关键内容准确",
              "只保留原文实际给出的细节或结果",
              "用自己的话连贯表达，不补入未说明的事实",
            ],
      supportedGoals: pronunciation
        ? ["从记忆写出本材料中的一个音节或短表达"]
        : single
          ? ["说清原句的主要意思，保留条件和否定"]
          : short
            ? [
                "说清材料的一项核心信息",
                "补充材料中的另一项信息；没有新信息时停在主旨",
              ]
            : [
                "说明材料正在讨论的事项",
                "补充原文实际给出的关键内容",
                "说明原文给出的结果或尚未确定的事项",
              ],
      extensionGoal: pronunciation
        ? "完成回忆后，再读写本材料中的另一个音节或短表达；只有一个时重复拼合，不扩写情节。"
        : single
          ? "完成复述后，再换一种表达说明原句已经给出的条件、否定或所指；没有条件时只改写已有意思，不新编理由。"
          : short
            ? "完成概括后，再补充一项原文已有细节，或重新连接已有信息；没有更多信息时只改写，不新编理由或结果。"
            : "完成摘要后，再说明原文已给出的一个条件或未确定事项；若另提出条件，明确是自己的补充，不冒充原文事实。",
    });
  }
  if (week >= 19 && tasks[0]?.kind !== "summary") {
    const source = section.lines;
    tasks.push({
      id: "current-summary",
      title: "书面摘要",
      kind: "summary",
      source: "current",
      prompt: `用 ${source.length <= 6 ? "1–3" : "4–6"} 句韩语概括「${section.label}」中人物正在处理的事项和实际给出的信息。只保留原文已说明的理由、结果或未确定事项，不假定双方一定存在分歧或达成协商。不要逐句抄写，统一书面语体。`,
      stimulus: [],
      referenceKo: [source[0]?.ko, source.at(-1)?.ko].filter(
        (line): line is string => !!line,
      ),
      referenceLineIds: [
        ...new Set(
          [source[0]?.id, source.at(-1)?.id].filter((id): id is string => !!id),
        ),
      ],
      referenceZh:
        "以下是原文开头和结尾，供核对场景及结果，并非完整摘要范文。复查你的摘要有没有遗漏主要理由或扩大结论。",
      checklist: [
        "人物的实际信息和目的没有被歪曲",
        "只归纳原文已说明的结果或未确定事项",
        "句子连贯、书面语体一致",
      ],
      supportedGoals: [
        "说清人物正在处理的事项",
        "补充人物实际给出的信息",
        "说明原文已给出的下一步或未确定事项",
      ],
      extensionGoal:
        "完成概括后，再换一种方式说明人物实际给出的信息；材料有未确定事项时可以提出核对建议，明确这是补充，不冒充已经发生的结果。",
    });
  }
  // Post-course material has its own current-scene tasks; do not relabel the
  // already available week-26 transfer task as a new week-27 assessment.
  if (lesson.week > 26) return tasks;
  const seed = DIALOGUE_TRANSFER_SCENARIOS[week - 1];
  tasks.push({
    id: `transfer-w${String(week).padStart(2, "0")}`,
    title: seed.title,
    kind: week >= 19 ? "argument" : "transfer",
    source: "new-scenario",
    prompt: seed.prompt,
    stimulus: [seed.stimulus],
    referenceKo: [seed.reference],
    referenceZh: seed.meaning,
    checklist: seed.goals,
    supportedGoals: seed.supportedGoals,
    ...(week >= 19
      ? {
          extensionGoal:
            "完成原任务后，再回应材料已经给出的顾虑，或说明建议成立所需的条件；自行提出的条件要明确标为补充，不编造原文反方意见。",
        }
      : {}),
  });
  const data = DIALOGUE_DATA_SCENARIOS.find((item) => item.week === week);
  if (data)
    tasks.push({
      id: `data-w${week}`,
      title: data.title,
      kind: "data",
      source: "new-scenario",
      prompt:
        "根据以下教学假设写 4–6 句韩语：准确描述数值、比较变化，再写这些数据不能说明什么。不添加原因或真实研究出处。使用书面语体。",
      stimulus: data.facts,
      referenceKo: [data.reference],
      referenceZh: data.meaning,
      checklist: [
        "数字、单位和比较基准正确",
        "人数、比例与因果没有混用",
        "说明缺失信息和结论边界",
      ],
      supportedGoals: [
        "描述材料给出的数值和单位",
        "按同一基准比较数值或变化",
        "说明材料没有提供的信息及结论边界",
      ],
    });
  return tasks;
}

export function originalDialoguePracticeLines(
  task: DialoguePracticeTask,
  part: "stimulus" | "reference",
): string[] {
  if (task.source !== "current") return [];
  return [
    ...new Set(
      part === "stimulus"
        ? (task.stimulusLineIds ?? [])
        : (task.referenceLineIds ?? []),
    ),
  ];
}
